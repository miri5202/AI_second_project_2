"""יוצר דאטהסט ב-LangSmith (מריצים פעם אחת)."""
from dotenv import load_dotenv
load_dotenv()

from langsmith import Client

DATASET_NAME = "or-books-support"

EXAMPLES = [
    ("מה שעות הפתיחה ביום שישי?", "ביום שישי החנות פתוחה 9:00-13:00."),
    ("אתם פתוחים בשבת?", "לא, בשבת ובחגים החנות סגורה."),
    ("כמה עולה משלוח להזמנה של 150 ש\"ח?", "25 ש\"ח, כי משלוח חינם רק מעל 200 ש\"ח."),
    ("הזמנתי ב-300 ש\"ח, אשלם על משלוח?", "לא, מעל 200 ש\"ח המשלוח חינם."),
    ("תוך כמה זמן מגיע משלוח?", "3-5 ימי עסקים."),
    ("קניתי ספר לפני 10 ימים, אפשר להחזיר ולקבל כסף?", "אפשר להחזיר עם קבלה וספר במצב חדש, אך מקבלים זיכוי בלבד ולא החזר כספי."),
    ("קניתי לפני 20 יום, אפשר להחזיר?", "לא, החזרות רק עד 14 יום מיום הקנייה."),
    ("אפשר להחזיר ספר שהזמנתי בהזמנה מיוחדת?", "לא, הזמנות מיוחדות אינן ניתנות להחזרה."),
    ("כמה עולה הקדשה מודפסת?", "15 ש\"ח, והיא מוסיפה יומיים לזמן המשלוח."),
    ("יש לכם סניף בחיפה?", "אין לי מידע על כך; יש לפנות לשירות בטלפון 03-0000000 או ב-service@or-books.example."),
    ("אתם עושים עטיפת מתנה?", "אין לי מידע על כך; יש לפנות לשירות הלקוחות בטלפון 03-0000000."),
    ("הזמנתי ספר עם הקדשה, מתי יגיע?", "5-7 ימי עסקים (3-5 ימים רגילים ועוד יומיים בגלל ההקדשה)."),
]

client = Client()
if client.has_dataset(dataset_name=DATASET_NAME):
    print("הדאטהסט כבר קיים")
else:
    ds = client.create_dataset(DATASET_NAME, description="שאלות לקוחות + תשובות ייחוס")
    client.create_examples(
        dataset_id=ds.id,
        examples=[{"inputs": {"question": q}, "outputs": {"answer": a}} for q, a in EXAMPLES],
    )
    print(f"נוצר דאטהסט עם {len(EXAMPLES)} דוגמאות")
